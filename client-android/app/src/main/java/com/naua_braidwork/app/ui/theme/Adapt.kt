package com.naua_braidwork.app.ui.theme

import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.LocalConfiguration
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Ширина окна в трёх классах.
 *
 * ## Зачем это вообще
 *
 * Экран не бывает «телефоном» или «планшетом». Он бывает шириной в окне
 * приложения: в разделённом экране, в окне рабочего стола, на развёрнутом
 * сгибе планшет превращается в узкую полосу, а телефон в окне — в широкий
 * прямоугольник. Решать по физическому экрану значит решать не по тому.
 *
 * Границы взяты официальные: 600 dp — граница между телефоном и всем, что
 * шире, дальше 840 dp — широкое окно. Класс нужен один, в одном месте, и
 * дальше передаётся вниз: размазывать проверки ширины по экранам — значит
 * через месяц получить четыре разных ответа на один и тот же вопрос.
 */
enum class ШиринаОкна(
    /** Нижняя граница класса в dp. */
    val от: Int,
) {
    /** Узкое окно: телефон, вертикально, половина экрана. */
    Узкий(0),

    /** Среднее окно: планшет вертикально, разворот телефона, узкое окно стола. */
    Средний(600),

    /** Широкое окно: планшет горизонтально, окно на ноутбуке. */
    Широкий(840);

    /** Строки текста не должны становиться нечитающе длинными. */
    val максШиринаСодержимого: Dp
        get() = when (this) {
            Узкий -> 640.dp
            Средний -> 720.dp
            Широкий -> 840.dp
        }

    /**
     * Поле от края экрана.
     *
     * На узком окне 20 dp — иначе на экране 360 dp текст получает треть
     * ширины. На широком 32 dp: 20 dp на планшете выглядит как обрезанный
     * край, а не как замысел.
     */
    val поле: Dp
        get() = when (this) {
            Узкий -> 20.dp
            Средний -> 28.dp
            Широкий -> 32.dp
        }

    /**
     * Сколько колонок ставить в сетке плиток.
     *
     * Одна колонка на телефоне, две на среднем окне, три на широком. Одна
     * колонка на планшете оставляет плитки растянутыми вчетверо, а четыре на
     * телефоне превращают их в узкие полоски, где значок больше подписи.
     */
    val колонки: Int
        get() = when (this) {
            Узкий -> 1
            Средний -> 2
            Широкий -> 3
        }

    companion object {
        /**
         * Класс по ширине окна в dp.
         *
         * Значение 0 при «неизвестной» ширине даёт узкий класс — самый
         * тесный. Это осознанно: в тесноте любой интерфейс ужимается, а
         * просторный — простаивает лишней пустотой.
         */
        fun поШирине(ширинаDp: Int): ШиринаОкна = when {
            ширинаDp >= Широкий.от -> Широкий
            ширинаDp >= Средний.от -> Средний
            else -> Узкий
        }
    }
}

/**
 * Текущий класс ширины окна.
 *
 * Единственное место в приложении, где ширина окна превращается в класс.
 * Экраны берут отсюда, а не читают `LocalConfiguration` сами: тогда все они
 * получают один и тот же ответ по построению, и разойтись не могут.
 *
 * ## Почему не CompositionLocal
 *
 * Оборачивать всё дерево в провайдер ради одного числа стоит вложенности в
 * `MainActivity` — а на ручной вложенности уже обжигались. Чтение
 * `LocalConfiguration` внутри composable дешёвое: это чтение
 * `CompositionLocal`, и при повороте экрана или изменении размера окна
 * пересобираются только те composable, что его читали.
 */
val ширинаОкна: ШиринаОкна
    @Composable
    get() = ШиринаОкна.поШирине(LocalConfiguration.current.screenWidthDp)
