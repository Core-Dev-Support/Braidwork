package com.naua_braidwork.app

import android.content.Context
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * Сопряжённые устройства: отпечаток ключа на каждый идентификатор.
 *
 * Ядро уже делает две вещи: сверяет объявленный идентификатор с ключом подписи
 * и проверяет подпись. Обе доказывают, что объявление не подделано, но ни одна
 * не говорит, **то** ли это устройство. Подделка, у которой есть ключ, — это
 * уже другое устройство, и отличить его без участия человека нечем.
 *
 * Хранилище и есть это участие: человек один раз сверяет отпечаток глазами и
 * решает, что это то самое устройство. Дальше приложение сверяет само и
 * предупреждает, если отпечаток изменился.
 *
 * ## Почему `SharedPreferences`
 *
 * Данных мало, пишутся редко, и лишняя зависимость в приложении, которое
 * собирается только на CI, стоила бы дороже. Настройки рядом хранятся так же.
 *
 * ## Что хранится и что нет
 *
 * Только отпечаток — 16 символов. Ни ключей, ни адресов, ни истории: всё это
 * можно получить заново, а хранить лишнее — значит расширять поверхность утечки
 * без нужды.
 */
class TrustStore private constructor(context: Context) {

    private val prefs = context.applicationContext
        .getSharedPreferences("braidwork-trust", Context.MODE_PRIVATE)

    /**
     * Отпечаток на идентификатор, в состоянии для Compose.
     *
     * Состояние, а не чтение по месту: экран показывал бы старое значение до
     * перерисовки, и строка «Доверие» выглядела бы сломанной сразу после
     * нажатия «Сопрячь».
     */
    var доверенные: Map<String, String> by mutableStateOf(emptyMap())
        private set

    init {
        перечитать()
    }

    private fun перечитать() {
        val всё = prefs.all
        val найдено = HashMap<String, String>()
        for ((ключ, значение) in всё) {
            // Префикс отсекается: в том же хранилище ключ лежит под именем
            // `_id_`, и без него отпечаток был бы смешан с идентификатором.
            if (ключ.startsWith(ПРЕФИКС) && значение is String) {
                найдено[ключ.removePrefix(ПРЕФИКС)] = значение
            }
        }
        доверенные = найдено
    }

    /** Отпечаток, сохранённый для устройства. `null` — устройство не сверено. */
    fun отпечаток(deviceId: String): String? = доверенные[deviceId]

    /**
     * Состояние доверия устройства.
     *
     * Различаются три случая, и различие существенно:
     *
     * - **Не сверено** — устройство в сети впервые. Ничего плохого, но
     *   приложение ещё не знает, что это то самое устройство.
     * - **Сопряжено** — отпечаток совпал с сохранённым. Это и есть доверие.
     * - **Отпечаток изменился** — устройство с тем же идентификатором пришло с
     *   другим ключом. Так бывает при законной ротации ключей и при подмене, и
     *   различить их автоматически нельзя. Требуется человек.
     */
    fun состояние(deviceId: String, отпечаток: String): Доверие {
        val сохранённый = доверенные[deviceId] ?: return Доверие.НЕ_СВЕРЕНО
        return if (сохранённый == отпечаток) {
            Доверие.СОПРЯЖЕНО
        } else {
            Доверие.ОТПЕЧАТОК_ИЗМЕНИЛСЯ
        }
    }

    /**
     * Запоминает отпечаток как свой.
     *
     * Перезаписывает прежний, и это осознанно: человек, нажавший «Сопрячь»,
     * решил, что новое устройство — то, что нужно. Молча отказывать было бы
     * хуже, чем спросить и позволить передумать, — а спроса здесь нет,
     * потому что решение принимает человек.
     */
    fun сопрячь(deviceId: String, отпечаток: String) {
        // Пустой отпечаток не сохраняется: он означает старое ядро напарника, и
        // запись «пусто» превратилась бы в ложное доверие при следующем же
        // объявлении с настоящим отпечатком.
        if (отпечаток.isBlank()) return

        prefs.edit().putString(ПРЕФИКС + deviceId, отпечаток).apply()
        перечитать()
    }

    /** Забывает устройство: приложение больше ему не доверяет. */
    fun забыть(deviceId: String) {
        prefs.edit().remove(ПРЕФИКС + deviceId).apply()
        перечитать()
    }

    /** Состояние доверия. Порядок совпадает с опасностью. */
    enum class Доверие {
        /** Устройство в сети, но человек его не сверял. */
        НЕ_СВЕРЕНО,

        /** Отпечаток совпал с сохранённым. */
        СОПРЯЖЕНО,

        /** Отпечаток изменился: законная ротация ключей или подмена. */
        ОТПЕЧАТОК_ИЗМЕНИЛСЯ,
    }

    companion object {
        /** Отличает ключи отпечатков от прочих записей того же хранилища. */
        private const val ПРЕФИКС = "fp_"

        @Volatile
        private var instance: TrustStore? = null

        /**
         * Единственный экземпляр на процесс.
         *
         * Отдельный на каждый экран означал бы отдельные копии доверия: одно
         * устройство считалось бы сопряжённым на карточке и несопряжённым на
         * экране сопряжения, и выглядело бы поломкой.
         */
        fun get(context: Context): TrustStore =
            instance ?: synchronized(this) {
                instance ?: TrustStore(context).also { instance = it }
            }
    }
}